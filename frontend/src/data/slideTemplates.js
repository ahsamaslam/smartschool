const inter = "'Inter', system-ui, sans-serif";
const geo = "'Georgia', 'Times New Roman', serif";
const mono = "'JetBrains Mono', 'Courier New', monospace";

function theme(base) {
  return {
    id: base.id,
    name: base.name,
    category: base.category,
    preview: base.preview,
    css: {
      slideBackground: base.bg,
      titleColor: base.tCol,
      titleSize: base.tSize ?? "38px",
      titleWeight: base.tWeight ?? "700",
      titleFont: base.tFont ?? inter,
      titleLetterSpacing: base.tTrack ?? "-0.02em",
      bodyColor: base.bCol,
      bodySize: base.bSize ?? "15px",
      bodyFont: base.bFont ?? inter,
      lineHeight: base.lh ?? "1.78",
      accentColor: base.accent,
      bulletChar: base.bullet ?? "•",
      padding: base.pad ?? "48px 56px",
      defaultAnimation: base.anim ?? "fade",
      numberColor: base.num ?? base.accent,
      tagBg: base.tagBg ?? `${base.accent}22`,
      tagColor: base.tagCol ?? base.accent,
      dividerColor: base.divider,
      highlightBg: base.hiBg,
      highlightBorder: base.hiBd,
      ...base.extra,
    },
  };
}

